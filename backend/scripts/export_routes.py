"""export_routes: writes app/ROUTES.md, the overview of every API route (method, path, who may call it, the file
with the route function). app/tests/test_routes_file.py fails when ROUTES.md is out of date, so after adding or
changing a route, run from backend\\:
    python -m scripts.export_routes
"""

from pathlib import Path

from fastapi.routing import APIRoute

from app.main import ROUTERS

OUT = Path(__file__).resolve().parents[1] / "app" / "ROUTES.md"
HEADER = """# API routes

Generated by `python -m scripts.export_routes` from the routers in `app/main.py` (ROUTERS). Do not edit by hand:
`app/tests/test_routes_file.py` fails when this file is out of date.

- **Change a route:** open its route file (last column). **Add a route:** copy `app/route.py.example` to
  `app/<feature>/f_routes/<name>.py`, add one line to that feature's `router.py`, then run the script above.
- **Who may call:** `key scope X` = an API key (or console role) with scope X (`key scope admin` = an admin key
  or a super admin only: supervisors may not even read); `admin` = the `admin` scope, or a supervisor's
  `admin:read` for GET; `admin or supervisor` = both may; `console login` = a person logged in to the console;
  `security password` = a super admin logged in to the console who unlocked the security password (8.6e-3,
  `app/tools/gate.py`; API keys never pass); `anyone` = no login.

| Method | Path | Who may call | Route file |
|---|---|---|---|
"""


def permission(route: APIRoute) -> str:
    """Who may call the route, read from its dependencies (require_scope("x"), require_admin, ...)."""
    found, todo = [], list(route.dependant.dependencies)
    while todo:
        dependency = todo.pop(0)
        call, name = dependency.call, getattr(dependency.call, "__name__", "")
        if name == "checker" and call.__closure__:  # require_scope("x") keeps x in its closure
            found += [f"key scope `{cell.cell_contents}`" for cell in call.__closure__ if isinstance(cell.cell_contents, str)]
        elif name == "require_admin":
            found.append("admin")
        elif name == "require_collection_creator":
            found.append("admin or supervisor")
        elif name == "require_console_user":
            found.append("console login")
        elif name == "require_unlocked":
            found.append("security password")
        todo += dependency.dependencies
    return ", ".join(dict.fromkeys(found)) or "anyone"


def routes_markdown() -> str:
    lines = []
    for router in ROUTERS:
        for route in router.routes:
            if isinstance(route, APIRoute):
                methods = ", ".join(sorted(route.methods))
                file = route.endpoint.__module__.replace(".", "/") + ".py"
                lines.append(f"| {methods} | `{route.path}` | {permission(route)} | `{file}` |")
    return HEADER + "\n".join(lines) + "\n"


def main() -> None:
    OUT.write_text(routes_markdown(), encoding="utf-8")
    print(f"wrote {OUT} ({routes_markdown().count('| `/') } routes)")


if __name__ == "__main__":
    main()
